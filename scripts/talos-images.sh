#!/usr/bin/env bash
# Generate the talos_images table in contexts/_template/facets/config-talos.yaml: the
# images that each Talos version pinned in the facets selects by default, as artifact
# tags. The table is the region between the BEGIN talos_images and END talos_images
# lines, and the script leaves the rest of the file unchanged.
#
#   scripts/talos-images.sh           regenerate the table
#   scripts/talos-images.sh --check   verify the table matches; non-zero on drift (CI)
#   scripts/talos-images.sh --verify  compare the table with talosctl image default (CI)
#
# The pinned versions are the literal talos_version and talos_image_tag values in
# contexts/_template/facets. The images come from the Talos source at each tag:
# pkg/images/list.go and pkg/machinery/constants/constants.go. The Kubernetes images
# are not in the table, because core pins the Kubernetes version and tags them there.
# --verify downloads talosctl for each pinned version, unless the talosctl on PATH is
# that version, and fails when its default images differ from the table.

set -euo pipefail

FACETS_DIR="contexts/_template/facets"
OUT="$FACETS_DIR/config-talos.yaml"
BEGIN_MARK="  # BEGIN talos_images: generated by task talos:images. Do not edit."
END_MARK="  # END talos_images"
SOURCE="https://raw.githubusercontent.com/siderolabs/talos"
MODE="${1:-}"

tmp=$(mktemp)
entries=$(mktemp)
bin_dir=$(mktemp -d)
trap 'rm -rf "$tmp" "$entries" "$bin_dir"' EXIT

# pinned_versions -> each Talos version that a facet pins, one per line, sorted
pinned_versions() {
  grep -hoE '^[[:space:]]*(talos_version: "[0-9]+\.[0-9]+\.[0-9]+"|talos_image_tag: "v[0-9]+\.[0-9]+\.[0-9]+")' "$FACETS_DIR"/*.yaml \
    | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | sort -uV
}

# constant <file> <name> -> the string value of a Go constant, or an error
constant() {
  local value
  value=$(grep -oE "^[[:space:]]*(const )?$2 = \"[^\"]+\"" "$1" | head -n1 | sed -E 's/.*"([^"]+)"/\1/')
  [ -n "$value" ] || { echo "constant $2 not found in the Talos source" >&2; exit 1; }
  printf '%s' "$value"
}

# images <version> -> "<key> <image reference>" lines for one Talos version
images() {
  local version="$1" list constants repo tag pause pairs repository name
  list=$(mktemp)
  constants=$(mktemp)
  curl -fsSL "$SOURCE/v$version/pkg/images/list.go" -o "$list"
  curl -fsSL "$SOURCE/v$version/pkg/machinery/constants/constants.go" -o "$constants"

  repo=$(constant "$constants" EtcdImage)
  tag=$(constant "$constants" DefaultEtcdVersion)
  echo "etcd $repo:$tag"
  repo=$(constant "$constants" CoreDNSImage)
  tag=$(constant "$constants" DefaultCoreDNSVersion)
  echo "coredns $repo:$tag"
  pause=$(constant "$list" DefaultSandboxImage)
  echo "pause $pause"

  # Images that list.go builds as fmt.Sprintf("<repository>:%s", constants.<Version>).
  pairs=$(grep -oE '"[a-z0-9./-]+:%s", constants\.[A-Za-z]+' "$list" | sed -E 's/"([^"]+):%s", constants\.([A-Za-z]+)/\1 \2/' | sort -u)
  [ -n "$pairs" ] || { echo "no fmt.Sprintf images found in pkg/images/list.go at v$version" >&2; exit 1; }
  while read -r repository name; do
    tag=$(constant "$constants" "$name")
    echo "${repository##*/} $repository:$tag"
  done <<< "$pairs"

  rm -f "$list" "$constants"
}

# talosctl_for <version> -> path to a talosctl binary of that version
talosctl_for() {
  local version="$1" os arch path
  if command -v talosctl >/dev/null && talosctl version --client --short 2>/dev/null | grep -qx "Talos v$version"; then
    command -v talosctl
    return
  fi
  os=$(uname -s | tr '[:upper:]' '[:lower:]')
  case "$(uname -m)" in
    x86_64 | amd64) arch=amd64 ;;
    aarch64 | arm64) arch=arm64 ;;
    *) echo "unsupported architecture $(uname -m)" >&2; exit 1 ;;
  esac
  path="$bin_dir/talosctl-$version"
  curl -fsSL -o "$path" "https://github.com/siderolabs/talos/releases/download/v$version/talosctl-$os-$arch"
  chmod +x "$path"
  echo "$path"
}

# expected_images <version> -> sorted image references that talosctl selects, minus Kubernetes
expected_images() {
  local bin
  bin=$(talosctl_for "$1")
  "$bin" image default \
    | grep -vE '/(kube-apiserver|kube-controller-manager|kube-scheduler|kube-proxy|kubelet):' \
    | sort
}

# table_images <version> -> sorted image references of one version in the table
table_images() {
  yq ".config[] | select(.name == \"talos_images\") | .value[\"$1\"] | to_entries | .[].value" "$OUT" | sort
}

if [ "$MODE" = "--verify" ]; then
  failed=0
  for version in $(pinned_versions); do
    if ! diff -u <(expected_images "$version") <(table_images "$version") > "$entries"; then
      echo "Talos $version: $OUT differs from talosctl image default:" >&2
      cat "$entries" >&2
      failed=1
    fi
  done
  [ "$failed" = 0 ] || exit 1
  echo "$OUT matches talosctl image default"
  exit 0
fi

versions=$(pinned_versions)
[ -n "$versions" ] || { echo "no pinned Talos versions found in $FACETS_DIR" >&2; exit 1; }
[ "$(grep -cxF "$BEGIN_MARK" "$OUT")" = 1 ] && [ "$(grep -cxF "$END_MARK" "$OUT")" = 1 ] \
  || { echo "$OUT needs one BEGIN talos_images line and one END talos_images line" >&2; exit 1; }

table=$(mktemp)
{
  echo "  - name: talos_images"
  echo "    value:"
  for version in $versions; do
    images "$version" > "$entries"
    echo "      \"$version\":"
    sort "$entries" | while read -r key reference; do
      echo "        # artifact: type=image name=${reference%:*}"
      echo "        $key: \"$reference\""
    done
  done
} > "$table"

# Replace the lines between the markers with the new table.
awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v table="$table" '
  $0 == begin { print; while ((getline line < table) > 0) print line; skip = 1; next }
  $0 == end { skip = 0 }
  !skip { print }
' "$OUT" > "$tmp"
rm -f "$table"

if [ "$MODE" = "--check" ]; then
  if ! diff -u "$OUT" "$tmp"; then
    echo "The talos_images table in $OUT is out of date. Run task talos:images." >&2
    exit 1
  fi
  exit 0
fi

cat "$tmp" > "$OUT"
echo "wrote the talos_images table in $OUT"
